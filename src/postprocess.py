"""
постобработка: подрезаем вероятности в [0, 1] на всякий случай.
"""

import numpy as np


def clip_prob(p: float, eps: float = 0.0) -> float:
    """
    Подрезаем значение, чтобы оно точно попало в [0, 1].
    eps > 0 слегка сжимает крайние значения, но в конце я его не использую —
    TTA уже нормально калибрует вероятности.
    """
    return float(np.clip(p, eps, 1.0 - eps))