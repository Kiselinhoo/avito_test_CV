"""
Классификатор ориентации текста на базе RapidOCR.

Задача: по кропу с текстом понять, нормальный он или перевёрнут на 180°.
RapidOCR в разных версиях отдаёт результат по-разному: то список,
то объект с полем cls_res. Здесь мы прячем эту разницу и всегда
возвращаем одно число p_180 от 0 до 1.
"""

from typing import Any         

import cv2                     
import numpy as np              
from rapidocr_onnxruntime import RapidOCR   


class OrientationClassifier:
    """Определяет, перевёрнут ли текст на 180°."""

    def __init__(self) -> None:
        # Создаём движок RapidOCR, но выключаем всё лишнее:
        # use_det=False — не ищем текстовые боксы (нам уже дали готовый кроп),
        # use_rec=False — не распознаём сам текст (нам нужна только ориентация),
        # use_cls=True  — включаем классификатор ориентации, ради него всё и затевается.
        # Так движок не тратит время на то, что нам не нужно.
        self._engine = RapidOCR(use_det=False, use_rec=False, use_cls=True)

    @staticmethod
    def _extract_p180(result: Any) -> float:
        """
        Достаёт p_180 из ответа RapidOCR.

        Разные версии библиотеки возвращают результат в разных форматах,
        поэтому приходится поддерживать оба:
          - старый API: result это список [(label, conf), ...]
          - новый API:  result это объект с полем result.cls_res
        Если что-то совсем непонятное — возвращаем нейтральное 0.5.
        """
        # Если модель ничего не вернула — не можем судить, ставим 0.5.
        if result is None:
            return 0.5

        # Новый API прячет результат в .cls_res, старый отдаёт список напрямую.
        # Проверяем, есть ли атрибут, и берём то, что нужно.
        cls_res = result.cls_res if hasattr(result, "cls_res") else result
        # Если список пустой — тоже ставим нейтральное значение.
        if not cls_res:
            return 0.5

        # Берём первый элемент. Дальше он может быть кортежем или словарём —
        # зависит от версии RapidOCR.
        first = cls_res[0]

        if isinstance(first, (tuple, list)) and len(first) >= 2:
            # Обычный случай: элемент это кортеж (label, confidence).
            label, conf = first[0], first[1]
        else:
            # На всякий случай — если пришёл словарь вида {"label": ..., "score": ...}.
            label = first.get("label", "0")
            conf = first.get("score", 0.5)

        # Приводим типы: label всегда строка, conf всегда float.
        label = str(label)
        conf = float(conf)

        # Логика: если модель сказала "180" — conf это и есть p_180.
        # Если сказала "0" — то p_180 это вероятность противоположного класса,
        # то есть 1 - conf. Так мы получаем именно вероятность "перевёрнут",
        # а не уверенность в том, что было предсказано.
        return conf if label == "180" else 1.0 - conf

    def _predict_once(self, img: np.ndarray) -> float:
        """
        Один прогон модели без TTA.

        engine возвращает кортеж (result, elapsed_time). Нам нужен только result,
        поэтому второй элемент игнорируем через "_".
        """
        result, _ = self._engine(img)
        return self._extract_p180(result)

    def predict(self, img: np.ndarray, tta: bool = True) -> float:
        """
        Предсказание p_180 с опциональным TTA.

        Если tta=False — просто один прогон, быстро, но менее стабильно.

        Если tta=True (по умолчанию) — подаём картинку дважды:
          1) как есть,
          2) повёрнутую на 180°.
        Смысл: если оригинал нормальный, то перевёрнутая версия должна быть
        "перевёрнутой", и наоборот. То есть два предсказания говорят об одном
        и том же с разных сторон, и их можно усреднить.

        Для повёрнутой картинки модель даёт вероятность, что "это 180°".
        Но относительно оригинала это означает обратное — поэтому берём 1 - p_rot.
        Итог: p_180 = (p_orig + (1 - p_rot)) / 2.

        На практике TTA даёт +0.017 к метрике 1 - Brier за счёт того,
        что вероятности становятся честнее (лучше калиброваны).
        """
        # Сначала смотрим на оригинал — это основное предсказание.
        p_orig = self._predict_once(img)

        # Если TTA выключен — отдаём как есть.
        if not tta:
            return p_orig

        # Крутим картинку на 180° и получаем вторую независимую оценку.
        rotated = cv2.rotate(img, cv2.ROTATE_180)
        p_rot = self._predict_once(rotated)

        # Приводим p_rot к системе координат оригинала и усредняем с p_orig.
        return 0.5 * (p_orig + (1.0 - p_rot))